def build_netcdf_dataset(
        met_df: pd.DataFrame,
        meta: Mapping[str, Any] | None = None,
        *,
        parameters: Mapping[str, Mapping[str, Any]] | None = None,
        dataframes: dict[str, pd.DataFrame] | None = None,
        instrument_library_path: str | None = None,
) -> xr.Dataset:
    """
    Build a CF-1.10 timeSeries Dataset with provenance metadata.

    - Auto-generates methodology from source type
    - Introspects dataframes to document actual processing
    - Merges instrument library specs with config metadata
    - Adds streamlined global attributes
    - Documents quality assessment

    Args:
        met_df: DataFrame with meteorological data
        meta: Metadata dict (latitude, longitude, elevation_m, title, institution, etc.)
        parameters: Parameter configurations from config
        dataframes: Optional dict of source dataframes for introspection
        instrument_library_path: Optional path to custom instrument library

    Returns:
        xarray Dataset with rich metadata
    """
    if not isinstance(met_df.index, pd.DatetimeIndex):
        raise TypeError("met_df must be indexed by a pandas.DatetimeIndex")

    parameters = parameters or {}
    meta = dict(meta or {})
    dataframes = dataframes or {}

    # Load instrument library if specified
    library = None
    if instrument_library_path:
        try:
            library = InstrumentLibrary(instrument_library_path)
            logger.info(f"Loaded instrument library: {library}")
        except Exception as e:
            logger.warning(f"Failed to load instrument library: {e}")
    else:
        # Try to load default library (optional)
        try:
            library = InstrumentLibrary()
            logger.debug(f"Loaded default instrument library: {library}")
        except Exception as e:
            logger.debug(f"No default instrument library available: {e}")

    # coords: time, nv ----------------------------------------------------------
    time = _normalize_time_index(met_df.index)
    ds = xr.Dataset(coords={
        "time": ("time", time.values),
        "nv": ("nv", np.array([0, 1], dtype=int)),
    })
    ds["time"].attrs.update({
        "standard_name": "time",
        "long_name": "time of measurement",
        "axis": "T",
        "bounds": "time_bnds",
    })

    # time bounds: [start, start+step)
    step = _infer_step(time)
    tb = np.stack([time.values, (time + step).values], axis=1)
    ds["time_bnds"] = xr.DataArray(tb, dims=("time", "nv"))
    ds["time_bnds"].attrs.update({
        "long_name": "start and end of time interval",
        "comment": "Left-closed, right-open bounds: [start, end).",
    })

    # globals: CF compliance
    ds.attrs.update({"Conventions": "CF-1.10", "featureType": "timeSeries"})

    # Add streamlined global attributes
    _add_streamlined_global_attrs(ds, meta, parameters)

    def _var(name: str, values: np.ndarray, attrs: Mapping[str, Any]) -> None:
        ds[name] = xr.DataArray(values, dims=("time",))
        ds[name].attrs.update(dict(attrs))

    # Accept internal parameter keys OR legacy column labels
    def _vals_col(param_key: str, *, dtype=float) -> np.ndarray | None:
        if param_key in met_df.columns:
            return met_df[param_key].to_numpy(dtype=dtype)
        legacy = default_col_names.get(param_key)
        if legacy and legacy in met_df.columns:
            return met_df[legacy].to_numpy(dtype=dtype)
        return None

    def _has_col(param_key: str) -> bool:
        return _vals_col(param_key) is not None

    # --- Core meteorology with CF-standard base attributes --------------------
    if _has_col("pressure"):
        _var("air_pressure", _vals_col("pressure") * 100.0,
             {"standard_name": "air_pressure", "long_name": "air pressure",
              "units": "Pa", "cell_methods": "time: mean"})

    if _has_col("temperature"):
        _var("air_temperature", _vals_col("temperature"),
             {"standard_name": "air_temperature", "long_name": "air temperature",
              "units": "degC", "cell_methods": "time: mean"})

    if _has_col("relative_humidity"):
        _var("relative_humidity", _vals_col("relative_humidity") / 100.0,
             {"standard_name": "relative_humidity",
              "long_name": "relative humidity (fraction)",
              "units": "1", "cell_methods": "time: mean"})

    if _has_col("wind_speed"):
        _var("wind_speed", _vals_col("wind_speed"),
             {"standard_name": "wind_speed", "long_name": "wind speed",
              "units": "m s-1", "cell_methods": "time: mean"})

    if _has_col("wind_direction"):
        _var("wind_from_direction", _vals_col("wind_direction"),
             {"standard_name": "wind_from_direction",
              "long_name": "wind from direction",
              "units": "degree", "cell_methods": "time: mean"})

    if _has_col("precipitation"):
        _var("precipitation_amount", _vals_col("precipitation"),
             {"standard_name": "precipitation_amount",
              "long_name": "precipitation amount",
              "units": "kg m-2", "cell_methods": "time: sum"})

    # --- Short-wave & long-wave ------------------------------------------------
    if _has_col("global_shortwave"):
        _var("surface_downwelling_shortwave_flux_in_air", _vals_col("global_shortwave"),
             {"standard_name": "surface_downwelling_shortwave_flux_in_air",
              "long_name": "global shortwave flux",
              "units": "W m-2", "cell_methods": "time: mean"})

    if _has_col("diffuse_shortwave"):
        _var("surface_diffuse_downwelling_shortwave_flux_in_air", _vals_col("diffuse_shortwave"),
             {"standard_name": "surface_diffuse_downwelling_shortwave_flux_in_air",
              "long_name": "diffuse shortwave flux",
              "units": "W m-2", "cell_methods": "time: mean"})

    if _has_col("downwelling_lwir"):
        _var("surface_downwelling_longwave_flux_in_air", _vals_col("downwelling_lwir"),
             {"standard_name": "surface_downwelling_longwave_flux_in_air",
              "long_name": "downwelling longwave flux",
              "units": "W m-2", "cell_methods": "time: mean"})

    # Direct normal irradiance handling (existing DNI logic)
    if _has_col("direct_shortwave"):
        direct_vals = _vals_col("direct_shortwave")
        zenith_vals = _vals_col("solar_zenith")

        if zenith_vals is not None:
            # Have zenith: BHI = DNI * cos(zenith)
            zen_rad = np.deg2rad(zenith_vals)
            bhi = direct_vals * np.cos(zen_rad)
            _var("surface_direct_along_beam_shortwave_flux_in_air", bhi,
                 {"standard_name": "surface_direct_along_beam_shortwave_flux_in_air",
                  "long_name": "beam horizontal irradiance (BHI)",
                  "units": "W m-2", "cell_methods": "time: mean",
                  "comment": "BHI computed as DNI * cos(solar_zenith_angle)"})

            _var("surface_direct_along_beam_normal_shortwave_flux_in_air", direct_vals,
                 {"standard_name": "surface_direct_along_beam_normal_shortwave_flux_in_air",
                  "long_name": "direct normal irradiance (DNI)",
                  "units": "W m-2", "cell_methods": "time: mean"})
        else:
            # No zenith: assume direct values are DNI
            _var("surface_direct_along_beam_shortwave_flux_in_air", direct_vals,
                 {"standard_name": "surface_direct_along_beam_shortwave_flux_in_air",
                  "long_name": "direct beam irradiance",
                  "units": "W m-2", "cell_methods": "time: mean",
                  "comment": "Direct beam values (DNI or BHI depending on source)"})

    # --- Add provenance to variables --------------------------------
    if parameters:
        for param_name, param_config in parameters.items():
            cf_var = _PARAM_TO_CF.get(param_name)
            if not cf_var or cf_var not in ds:
                continue

            # Get metadata from config
            config_metadata = param_config.get("metadata", {})

            # Merge with instrument library if available
            merged_metadata = merge_instrument_metadata(library, config_metadata) if library else config_metadata

            # Determine source and add appropriate provenance
            source = param_config.get("source", "").lower()

            if source in ("met", "station"):
                _add_station_provenance(ds, cf_var, param_config, merged_metadata)

            elif source == "nldas2":
                _add_nldas2_provenance(ds, cf_var, param_config, merged_metadata)

            elif source.startswith("pvlib"):
                _add_pvlib_provenance(ds, cf_var, param_config, merged_metadata, dataframes)

            elif source in ("global_fraction", "global_coszenith", "brunt"):
                _add_derived_provenance(ds, cf_var, param_config, merged_metadata)

            else:
                # Generic provenance for other sources
                if merged_metadata.get("comment"):
                    ds[cf_var].attrs["comment"] = merged_metadata["comment"]
                _add_quality_assessment(ds, cf_var)

    # --- Optional visibility & aerosol -----------------------------------------
    if _has_col("visibility"):
        vis = _vals_col("visibility")
        if vis is not None:
            vis = np.where(np.asarray(vis, float) < 0.0, np.nan, vis)
            _var("visibility_in_air", vis,
                 {"standard_name": "visibility_in_air", "long_name": "visibility",
                  "units": "m", "cell_methods": "time: mean"})

    if _has_col("aerosol"):
        aer = _vals_col("aerosol")
        if aer is not None:
            _var("aerosol_legacy", aer,
                 {"long_name": "legacy aerosol indicator from .met",
                  "units": str(default_met_units.get("aerosol", "")),
                  "comment": "Not CF AOD; preserved for provenance."})

    # ---- convenience time variables -------------------------------------------
    iso = pd.DatetimeIndex(time).strftime("%Y-%m-%dT%H:%M:%SZ").to_numpy(dtype=object)
    _var("iso_time", iso, {"long_name": "timestamp ISO8601 (UTC)"})

    _var("day_of_year", pd.Series(time).dt.dayofyear.to_numpy(),
         {"long_name": "day of year (1..366)", "units": "1"})

    # ---- Coverage statistics ---------------------------------------------------
    present_core = [v for v in _CORE_VARS if v in ds]
    if present_core:
        fracs = []
        for v in present_core:
            arr = ds[v].values
            valid = np.count_nonzero(~np.isnan(arr)) if np.issubdtype(arr.dtype, np.floating) else arr.size
            fracs.append(float(valid) / float(arr.size))
        min_frac = float(min(fracs)) if fracs else 1.0
        ds.attrs["coverage_min_fraction_core"] = min_frac
        ds.attrs["coverage_ok"] = int(min_frac >= _COVERAGE_THRESHOLD)

    return ds


