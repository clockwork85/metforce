def _detect_sources_from_parameters(parameters: dict[str, Any]) -> list[str]:
    """
    Detect unique data sources from parameters configuration.

    Returns list of source identifiers for global 'source' attribute.
    """
    sources = set()

    for param_config in parameters.values():
        source = param_config.get("source", "").lower()

        # Normalize source names
        if source == "met" or source == "station":
            sources.add("weather_station")
        elif source == "nldas2":
            sources.add("nldas2")
        elif source.startswith("pvlib"):
            sources.add("pvlib_model")
        elif source in ("global_fraction", "global_coszenith"):
            sources.add("derived")
        elif source == "brunt":
            sources.add("derived")
        elif source:
            sources.add(source)

    return sorted(sources)


def _add_streamlined_global_attrs(
        ds: xr.Dataset,
        meta: dict[str, Any],
        parameters: dict[str, Any]
) -> None:
    """
    Add streamlined global attributes

    - Conventions, featureType (CF compliance) - already set
    - title, institution (user-specified)
    - processing_level (hard-coded to 2)
    - history (auto-generated timestamp)
    - source (auto-detected from parameters)
    - geospatial info (from meta)
    - comment (optional, from output config)
    """
    # User-specified core metadata
    if meta.get("title"):
        ds.attrs["title"] = meta["title"]

    if meta.get("institution"):
        ds.attrs["institution"] = meta["institution"]

    if meta.get("comment"):
        ds.attrs["comment"] = meta["comment"]

    # Processing level (hard-coded to 2 per spec - NASA specifications that shouldn't matter to us right now
    ds.attrs["processing_level"] = "2"

    # History (auto-generated)
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    ds.attrs["history"] = f"{timestamp}: Generated by metforce"

    # Source (auto-detected)
    sources = _detect_sources_from_parameters(parameters)
    if sources:
        ds.attrs["source"] = " ".join(sources)

    # Geospatial (from meta)
    if meta.get("latitude") is not None:
        ds.attrs["geospatial_latitude"] = float(meta["latitude"])
    if meta.get("longitude") is not None:
        ds.attrs["geospatial_longitude"] = float(meta["longitude"])
    if meta.get("elevation_m") is not None:
        elev = float(meta["elevation_m"])
        ds.attrs["geospatial_vertical_min"] = elev
        ds.attrs["geospatial_vertical_max"] = elev
        ds.attrs["geospatial_vertical_units"] = "m"
        ds.attrs["geospatial_vertical_positive"] = "up"


def _add_station_provenance(
        ds: xr.Dataset,
        cf_var: str,
        param_config: dict[str, Any],
        merged_metadata: dict[str, Any]
) -> None:
    """
    Add provenance for station-measured variables.

    Documents:
    - Measurement type (in situ)
    - Instrument specifications (from library if available)
    - Deployment details (from config)
    - Quality assessment
    """
    ds[cf_var].attrs["source"] = "station"
    ds[cf_var].attrs["measurement_type"] = "in_situ"

    # Add instrument specs if available
    if merged_metadata.get("manufacturer"):
        ds[cf_var].attrs["instrument_manufacturer"] = merged_metadata["manufacturer"]

    if merged_metadata.get("model"):
        ds[cf_var].attrs["instrument_model"] = merged_metadata["model"]

    # Add key specs based on instrument type
    for spec_key in ["accuracy", "spectral_range", "temperature_range",
                     "measurement_range", "response_time", "calibration_uncertainty"]:
        if merged_metadata.get(spec_key):
            ds[cf_var].attrs[spec_key] = str(merged_metadata[spec_key])

    # Deployment details
    if merged_metadata.get("serial_number"):
        ds[cf_var].attrs["serial_number"] = merged_metadata["serial_number"]

    if merged_metadata.get("installation_height") is not None:
        ds[cf_var].attrs["sensor_height"] = f"{merged_metadata['installation_height']} m"
    elif merged_metadata.get("measurement_height") is not None:
        ds[cf_var].attrs["sensor_height"] = f"{merged_metadata['measurement_height']} m"

    # Auto-generate comment
    auto_comment = _generate_station_comment(merged_metadata)

    # Merge with user comment (append by default)
    user_comment = merged_metadata.get("comment", "")
    comment_replace = merged_metadata.get("comment_replace")

    if comment_replace:
        # Rare: full override
        ds[cf_var].attrs["comment"] = comment_replace
    elif user_comment:
        # Common: append
        ds[cf_var].attrs["comment"] = f"{auto_comment} {user_comment}"
    else:
        # Default: just auto
        ds[cf_var].attrs["comment"] = auto_comment

    # Quality assessment
    _add_quality_assessment(ds, cf_var)


def _generate_station_comment(metadata: dict[str, Any]) -> str:
    """Generate auto comment for station measurements."""
    instrument_desc = ""
    if metadata.get("manufacturer") and metadata.get("model"):
        instrument_desc = f" using {metadata['manufacturer']} {metadata['model']}"

    measurement_type = "Direct measurement from weather station"

    return f"{measurement_type}{instrument_desc}."


def _add_nldas2_provenance(
        ds: xr.Dataset,
        cf_var: str,
        param_config: dict[str, Any],
        merged_metadata: dict[str, Any]
) -> None:
    """
    Add provenance for NLDAS2 reanalysis variables.

    Documents:
    - Data type (reanalysis)
    - Model system
    - Spatial/temporal interpolation
    - References
    """
    ds[cf_var].attrs["source"] = "nldas2"
    ds[cf_var].attrs["data_type"] = "reanalysis"
    ds[cf_var].attrs["model"] = "NLDAS-2 (North American Land Data Assimilation System)"
    ds[cf_var].attrs["spatial_resolution"] = "0.125 degree (~12.5 km)"
    ds[cf_var].attrs["temporal_resolution"] = "1 hour"

    # Auto-generate comment
    auto_comment = (
        "Derived from NLDAS-2 reanalysis data. "
        "Spatially interpolated to site location. "
        "Hourly temporal resolution."
    )

    # Merge with user comment
    user_comment = merged_metadata.get("comment", "")
    comment_replace = merged_metadata.get("comment_replace")

    if comment_replace:
        ds[cf_var].attrs["comment"] = comment_replace
    elif user_comment:
        ds[cf_var].attrs["comment"] = f"{auto_comment} {user_comment}"
    else:
        ds[cf_var].attrs["comment"] = auto_comment

    # References
    default_ref = "doi:10.1175/JCLI-D-20-0982.1"
    if merged_metadata.get("references"):
        ds[cf_var].attrs["references"] = f"{default_ref}, {merged_metadata['references']}"
    else:
        ds[cf_var].attrs["references"] = default_ref

    # Quality assessment
    _add_quality_assessment(ds, cf_var)


def _add_pvlib_provenance(
        ds: xr.Dataset,
        cf_var: str,
        param_config: dict[str, Any],
        merged_metadata: dict[str, Any],
        dataframes: dict[str, pd.DataFrame] | None = None
) -> None:
    """
    Add provenance for pvlib-derived solar radiation variables.

    Introspects dataframes to document actual inputs and corrections.

    Documents:
    - Data type (derived)
    - Method (pvlib function)
    - Atmospheric corrections applied
    - Input data sources
    - References
    """
    ds[cf_var].attrs["source"] = "pvlib"
    ds[cf_var].attrs["data_type"] = "derived"

    # Determine pvlib method from source
    source = param_config.get("source", "").lower()
    if "dirindex" in source:
        method = "pvlib.irradiance.dirindex (Perez-Ineichen decomposition)"
        ref = "Perez et al. (1990) doi:10.1016/0038-092X(90)90055-H"
    elif "disc" in source:
        method = "pvlib.irradiance.disc (DISC decomposition model)"
        ref = "Maxwell (1987) SERI/TR-215-3087"
    else:
        method = f"pvlib ({source})"
        ref = "pvlib documentation: https://pvlib-python.readthedocs.io"

    ds[cf_var].attrs["method"] = method

    # Introspect dataframes to determine atmospheric corrections
    corrections_applied = []
    pressure_source = None
    dew_point_method = None

    if dataframes:
        # Check for pressure data
        for df_key in ["MET", "met", "station"]:
            df = dataframes.get(df_key)
            if df is not None:
                if "pressure" in df.columns or "BP_mbar" in df.columns:
                    corrections_applied.append("surface_pressure")
                    pressure_source = "station barometer"
                    break

        # Check for temperature and humidity (implies dew point)
        has_temp = False
        has_rh = False
        for df_key in ["MET", "met", "station"]:
            df = dataframes.get(df_key)
            if df is not None:
                if "temperature" in df.columns or "AirT_2M" in df.columns:
                    has_temp = True
                if "relative_humidity" in df.columns or "RH" in df.columns:
                    has_rh = True

        if has_temp and has_rh:
            corrections_applied.append("dew_point_temperature")
            dew_point_method = "computed from air temperature and relative humidity"

    if corrections_applied:
        ds[cf_var].attrs["atmospheric_corrections"] = " ".join(corrections_applied)

        if pressure_source:
            ds[cf_var].attrs["pressure_source"] = pressure_source

        if dew_point_method:
            ds[cf_var].attrs["dew_point_method"] = dew_point_method

    # Auto-generate comment
    corrections_desc = ""
    if corrections_applied:
        corr_list = ", ".join(corrections_applied)
        corrections_desc = f" Atmospheric corrections applied for {corr_list}."

    auto_comment = f"Derived using {method}.{corrections_desc}"

    # Merge with user comment
    user_comment = merged_metadata.get("comment", "")
    comment_replace = merged_metadata.get("comment_replace")

    if comment_replace:
        ds[cf_var].attrs["comment"] = comment_replace
    elif user_comment:
        ds[cf_var].attrs["comment"] = f"{auto_comment} {user_comment}"
    else:
        ds[cf_var].attrs["comment"] = auto_comment

    # References
    if merged_metadata.get("references"):
        ds[cf_var].attrs["references"] = f"{ref}, {merged_metadata['references']}"
    else:
        ds[cf_var].attrs["references"] = ref

    # Quality assessment
    _add_quality_assessment(ds, cf_var)


def _add_derived_provenance(
        ds: xr.Dataset,
        cf_var: str,
        param_config: dict[str, Any],
        merged_metadata: dict[str, Any]
) -> None:
    """
    Add provenance for derived variables (global_fraction, brunt, etc.).

    Documents:
    - Data type (derived)
    - Method description
    - References if applicable
    """
    ds[cf_var].attrs["source"] = param_config.get("source", "derived")
    ds[cf_var].attrs["data_type"] = "derived"

    # Auto-generate comment based on source
    source = param_config.get("source", "").lower()
    if "global_fraction" in source:
        auto_comment = "Derived from global shortwave radiation using fixed diffuse fraction."
    elif "global_coszenith" in source:
        auto_comment = "Derived from global shortwave radiation using cosine of solar zenith angle."
    elif "brunt" in source:
        auto_comment = "Derived using Brunt equation from temperature and vapor pressure."
    else:
        auto_comment = f"Derived from {source}."

    # Merge with user comment
    user_comment = merged_metadata.get("comment", "")
    comment_replace = merged_metadata.get("comment_replace")

    if comment_replace:
        ds[cf_var].attrs["comment"] = comment_replace
    elif user_comment:
        ds[cf_var].attrs["comment"] = f"{auto_comment} {user_comment}"
    else:
        ds[cf_var].attrs["comment"] = auto_comment

    # References if provided
    if merged_metadata.get("references"):
        ds[cf_var].attrs["references"] = merged_metadata["references"]

    # Quality assessment
    _add_quality_assessment(ds, cf_var)


def _add_quality_assessment(ds: xr.Dataset, cf_var: str) -> None:
    """
    Add quality assessment to variable.

    Phase 3 approach: Document quality in attributes.
    Phase 5 will add QC arrays only when quality varies.
    """
    values = ds[cf_var].values
    has_missing = np.any(np.isnan(values)) if np.issubdtype(values.dtype, np.floating) else False

    if not has_missing:
        # Homogeneous quality
        ds[cf_var].attrs["quality_assessment"] = "All values consistent quality"
    else:
        # Variable quality - note coverage in attribute
        valid_pct = 100 * np.count_nonzero(~np.isnan(values)) / len(values)
        ds[cf_var].attrs["quality_assessment"] = f"Data coverage: {valid_pct:.1f}%"


